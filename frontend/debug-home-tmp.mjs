import { chromium } from '@playwright/test'
const ok = body => ({ status: 200, contentType: 'application/json', body: JSON.stringify({ code: 200, message: 'ok', data: body, timestamp: new Date().toISOString() }) })
const browser = await chromium.launch()
const context = await browser.newContext()
await context.addInitScript(() => {
  localStorage.setItem('token', 'smoke-token')
  localStorage.setItem('user', JSON.stringify({ id: 1, username: 'smoke', realName: '冒烟', role: 'DIRECTOR' }))
})
const page = await context.newPage()
page.on('pageerror', e => console.log('PAGEERROR', String(e)))
await page.route('**/api/**', route => route.fulfill(ok([])))
await page.goto('http://localhost:4173/', { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(2500)
console.log('secondary-nav count:', await page.locator('.secondary-nav').count())
console.log('secondary-menu-item count:', await page.locator('.secondary-menu-item').count())
console.log('visible:', await page.locator('.secondary-nav').isVisible().catch(e => 'ERR ' + e.message))
console.log('menu labels:', (await page.locator('.secondary-menu-item').allInnerTexts()).join('|'))
console.log('primary sections:', (await page.locator('.primary-nav button').allInnerTexts()).join('|'))
await browser.close()
